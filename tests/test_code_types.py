"""CODE.5 fixtures run in disposable source trees; no model or network required after build."""
import json
import pathlib
import subprocess
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
DLL = ROOT / 'harness/tools/code/bin/Debug/net9.0/CheckTypes.dll'

class TypeCheckTests(unittest.TestCase):
    def run_fixture(self, filename, source, expected, old=None):
        with tempfile.TemporaryDirectory() as folder:
            root = pathlib.Path(folder)
            (root / filename).write_text(source, encoding='utf-8')
            args = ['dotnet', str(DLL), filename]
            if old is not None:
                baseline = root / 'baseline'
                baseline.mkdir()
                (baseline / filename).write_text(old, encoding='utf-8')
                args += ['--baseline', str(baseline)]
            run = subprocess.run(args, cwd=root, capture_output=True, text=True, timeout=30)
            self.assertEqual(run.returncode, expected, run.stdout + run.stderr)
            return json.loads(run.stdout)

    def test_structural_cases(self):
        fixtures = [
            ('Widget.cs', 'namespace Domain; public class Widget {}', 0),
            ('Widget.cs', 'class Widget {} class Extra {}', 1),
            ('Wrong.cs', 'record Widget(int Value);', 1),
            ('Widget.cs', 'class Widget { private enum State { Ready } }', 0),
            ('Widget.cs', 'class Widget { enum State { Ready } }', 0),
            ('Widget.cs', 'class Widget { public enum State { Ready } }', 1),
            ('Widget.Part.cs', 'partial class Widget {}', 0),
            ('Widget.Part.cs', 'class Widget {}', 1),
            ('Generated.g.cs', 'class First {} class Second {}', 0),
            ('Generated.cs', '// <auto-generated/>\nclass First {} class Second {}', 0),
            ('Widget.cs', 'class Widget { string Value = "class Fake {}"; }', 0),
            ('Callback.cs', 'public delegate void Callback();', 0),
            ('Widget.cs', 'class Widget {', 2),
        ]
        for filename, source, expected in fixtures:
            with self.subTest(source=source):
                self.run_fixture(filename, source, expected)

    def test_inherited_versus_changed(self):
        old = 'class Widget {} class Legacy {}'
        data = self.run_fixture('Widget.cs', old, 0, old)
        self.assertEqual(data['findings'], [])
        data = self.run_fixture('Widget.cs', old + ' class Added {}', 1, old)
        self.assertEqual([f['type'] for f in data['findings']], ['Added'])

if __name__ == '__main__':
    unittest.main()

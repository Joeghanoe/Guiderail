using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

// Explicit files only: callers choose the audit scope; a baseline preserves inherited violations.
string? baseline = null;
string[]? symbols = null;
var files = new List<string>();
for (var i = 0; i < args.Length; i++)
{
    if (args[i] is "--baseline" or "--symbols")
    {
        var option = args[i];
        if (++i == args.Length || args[i].StartsWith("--")
            || (option == "--baseline" ? baseline is not null : symbols is not null))
            return Usage();
        if (option == "--baseline") baseline = args[i];
        else symbols = args[i] == "none" ? [] : args[i].Split(',');
    }
    else if (args[i].StartsWith("--")) return Usage();
    else files.Add(args[i]);
}
if (files.Count == 0 || symbols?.Any(s => !SyntaxFacts.IsValidIdentifier(s)) == true) return Usage();
var options = new CSharpParseOptions(preprocessorSymbols: symbols ?? []);
var inheritedFindings = new List<object>();
var findings = new List<object>();
var evidence = new List<object>();
var errors = new List<string>();
if (baseline is not null && !Directory.Exists(baseline))
{
    Console.Error.WriteLine("Baseline directory does not exist.");
    return 2;
}
foreach (var file in files)
{
    if (Path.IsPathRooted(file) || file.Split('/', '\\').Contains("..") || !file.EndsWith(".cs"))
    {
        errors.Add($"Expected a relative C# path: {file}");
        continue;
    }
    try
    {
        var text = File.ReadAllText(file);
        var generated = file.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || file.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || text.Split('\n').Take(5).Any(line => line.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));
        if (generated) { evidence.Add(new { path = file, status = "not-applicable", reason = "generated" }); continue; }
        var tree = CSharpSyntaxTree.ParseText(text, options);
        if (symbols is null && tree.GetRoot().DescendantTrivia(descendIntoTrivia: true).Any(t => t.IsKind(SyntaxKind.IfDirectiveTrivia)))
        {
            errors.Add($"Conditional compilation requires --symbols (use none for no symbols): {file}");
            continue;
        }
        if (tree.GetDiagnostics().Any(d => d.Severity == DiagnosticSeverity.Error))
        {
            errors.Add($"Syntax errors: {file}");
            continue;
        }
        var declarations = Types(tree.GetRoot());
        var oldFile = baseline is null ? null : Path.Combine(baseline, file);
        var oldTree = oldFile is not null && File.Exists(oldFile)
            ? CSharpSyntaxTree.ParseText(File.ReadAllText(oldFile), options) : null;
        if (symbols is null && oldTree?.GetRoot().DescendantTrivia(descendIntoTrivia: true).Any(t => t.IsKind(SyntaxKind.IfDirectiveTrivia)) == true)
        {
            errors.Add($"Baseline conditional compilation requires --symbols: {file}");
            continue;
        }
        if (oldTree?.GetDiagnostics().Any(d => d.Severity == DiagnosticSeverity.Error) == true)
        {
            errors.Add($"Baseline syntax errors: {file}");
            continue;
        }
        var old = oldTree is null ? [] : Types(oldTree.GetRoot());
        foreach (var declaration in declarations)
        {
            // Identical declarations are inherited evidence, not introduced violations.
            var inherited = baseline is not null && old.Any(d => d.ToString() == declaration.ToString());
            var name = Name(declaration);
            var nested = declaration.Ancestors().OfType<BaseTypeDeclarationSyntax>().Any();
            var modifiers = declaration is BaseTypeDeclarationSyntax t ? t.Modifiers : ((DelegateDeclarationSyntax)declaration).Modifiers;
            var privateNested = nested && !modifiers.Any(SyntaxKind.ProtectedKeyword) && (modifiers.Any(SyntaxKind.PrivateKeyword)
                || (!modifiers.Any(SyntaxKind.PublicKeyword) && !modifiers.Any(SyntaxKind.InternalKeyword)
                    && !modifiers.Any(SyntaxKind.ProtectedKeyword) && declaration.Parent is TypeDeclarationSyntax parent
                    && !parent.IsKind(SyntaxKind.InterfaceDeclaration)));
            if (privateNested) continue;
            var stem = Path.GetFileNameWithoutExtension(file);
            var partial = modifiers.Any(SyntaxKind.PartialKeyword);
            var matchingName = stem == name || (partial && stem.StartsWith(name + ".", StringComparison.Ordinal));
            var topCount = declarations.Count(d => !d.Ancestors().OfType<BaseTypeDeclarationSyntax>().Any());
            // An untouched sibling may become mixed because another type was added; that is not an inherited defect.
            if (inherited && !nested && matchingName
                && old.Count(d => !d.Ancestors().OfType<BaseTypeDeclarationSyntax>().Any()) <= 1) continue;
            if (nested || topCount > 1 || !matchingName)
                (inherited ? inheritedFindings : findings).Add(new { path = file, line = tree.GetLineSpan(declaration.Span).StartLinePosition.Line + 1,
                    rule = "CODE.5", type = name, reason = nested ? "non-private nested type" : topCount > 1 ? "multiple top-level types" : "file name differs from type" });
        }
        evidence.Add(new { path = file, status = "checked" });
    }
    catch (IOException ex) { errors.Add($"{file}: {ex.Message}"); }
}
Console.WriteLine(JsonSerializer.Serialize(new { rule = "CODE.5", version = 2, symbols, coverage = symbols is null ? "unconditional-files" : "selected-configuration", mode = baseline is null ? "audit" : "change", findings, inheritedFindings, evidence, errors }, new JsonSerializerOptions { WriteIndented = true }));
return errors.Count > 0 ? 2 : findings.Count > 0 ? 1 : 0;

static List<MemberDeclarationSyntax> Types(SyntaxNode root) => root.DescendantNodes()
    .OfType<MemberDeclarationSyntax>().Where(n => n is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).ToList();
static string Name(MemberDeclarationSyntax node) => node is BaseTypeDeclarationSyntax t ? t.Identifier.ValueText : ((DelegateDeclarationSyntax)node).Identifier.ValueText;

static int Usage()
{
    Console.Error.WriteLine("Usage: CheckTypes <relative.cs>... [--baseline <source-tree>] [--symbols <A,B|none>]");
    return 2;
}
